#!/usr/bin/env node
/* AeyChhotu! — end-to-end API contract smoke test.
 *
 * Replaces the hand-run 18/18 curl sweep recorded in docs/9 with something
 * repeatable. Talks to a RUNNING backend and walks the real diner + kitchen
 * journey in order, asserting the contract envelope and the exact error
 * codes from docs/7-api-contract.md.
 *
 * Usage:
 *   1. terminal A:  cd backend && npm run dev
 *   2. terminal B:  cd backend && npm run smoke
 *
 *   SMOKE_BASE_URL=http://localhost:4000   (default)
 *   SMOKE_KEEP=1                           (leave the test order in place)
 *
 * Needs STAFF_PIN from backend/.env to log in as the kitchen.
 */

import "dotenv/config";
import pg from "pg";

const BASE = (process.env.SMOKE_BASE_URL ?? "http://localhost:4000").replace(/\/+$/, "");
/* A table QR can be regenerated by the admin console, which changes its code.
   SMOKE_TABLE_TOKEN lets CI point this journey at whichever live table it
   seeded, while the default stays the documented demo table.

   A table's code can also drift between seed runs (the admin console's
   "regenerate" rewrites it, and seed.sql only inserts a missing id). If the
   documented demo code is not in the database, the pre-flight below picks the
   first real table instead of failing every session check with
   TABLE_NOT_FOUND. An explicit SMOKE_TABLE_TOKEN is never overridden. */
let TABLE_TOKEN = process.env.SMOKE_TABLE_TOKEN ?? "k7x2p";
/* The isolation checks need a table that is NOT the one under test. Keeping
   the foreign token derived from the live list avoids the old bug where
   SMOKE_TABLE_TOKEN=m9b3x made the "foreign" request hit the same table. */
let FOREIGN_TABLE_TOKEN = process.env.SMOKE_FOREIGN_TABLE_TOKEN ?? "m9b3x";
const KEEP = Boolean(process.env.SMOKE_KEEP);

let passed = 0;
const failures = [];

function check(label, condition, detail = "") {
  if (condition) {
    passed += 1;
    console.log(`  ✅ ${label}`);
  } else {
    failures.push(label);
    console.log(`  ❌ ${label}${detail ? ` — ${detail}` : ""}`);
  }
}

function section(title) {
  console.log(`\n${title}`);
}

/** One HTTP call → { status, body }. Never throws on non-2xx. */
async function api(path, { method = "GET", body, token } = {}) {
  const headers = { Accept: "application/json" };
  if (body !== undefined) headers["Content-Type"] = "application/json";
  if (token) headers.Authorization = `Bearer ${token}`;

  const res = await fetch(`${BASE}${path}`, {
    method,
    headers,
    body: body !== undefined ? JSON.stringify(body) : undefined,
  });
  let json = null;
  if (res.status !== 204) json = await res.json().catch(() => null);
  return { status: res.status, body: json };
}

console.log(`[smoke] target ${BASE}`);

/* Pre-flight: start from a clean table.
   Without this the suite is order-dependent — a ticket left behind by an
   interrupted run makes the next run fail at E8 with a 409, and the cascade
   of red afterwards hides the real cause (this happened). Cheap to do, and it
   means CI can run the suites in any order, repeatedly. */
if (process.env.DATABASE_URL) {
  const client = new pg.Client({ connectionString: process.env.DATABASE_URL.trim() });
  try {
    await client.connect();

    /* Resolve the table codes against the live database: prefer the
       documented defaults when they exist, otherwise take what is there.
       An explicit SMOKE_* override above is never touched. */
    const { rows: tableRows } = await client.query(
      `SELECT code FROM restaurant_tables ORDER BY code`,
    );
    const codes = tableRows.map((row) => row.code);
    if (!process.env.SMOKE_TABLE_TOKEN) {
      TABLE_TOKEN = codes.includes("k7x2p") ? "k7x2p" : (codes[0] ?? TABLE_TOKEN);
    }
    if (!process.env.SMOKE_FOREIGN_TABLE_TOKEN) {
      FOREIGN_TABLE_TOKEN = codes.find((code) => code !== TABLE_TOKEN) ?? FOREIGN_TABLE_TOKEN;
    }

    const { rows } = await client.query(
      `DELETE FROM orders
        WHERE table_id = (SELECT id FROM restaurant_tables WHERE code = $1)
        RETURNING id`,
      [TABLE_TOKEN],
    );
    await client.query(
      `DELETE FROM cart_items
        WHERE table_id = (SELECT id FROM restaurant_tables WHERE code = $1)`,
      [TABLE_TOKEN],
    );
    await client.query(
      `DELETE FROM table_device_presence
        WHERE table_id = (SELECT id FROM restaurant_tables WHERE code = $1)`,
      [TABLE_TOKEN],
    );
    // A clean table also means a clean SESSION: without this a credential
    // minted by an interrupted run would survive into this one.
    await client.query(
      `UPDATE restaurant_tables
          SET status = 'empty', session_pin = NULL, session_secret = NULL,
              failed_pin_attempts = 0, session_started_at = NULL,
              bill_status = 'unrequested', bill_requested_at = NULL, bill_paid_at = NULL
        WHERE code = $1`,
      [TABLE_TOKEN],
    );
    if (rows.length > 0) {
      console.log(`[smoke] pre-flight: cleared ${rows.length} leftover order(s)`);
    }
  } catch (err) {
    console.warn(`[smoke] pre-flight reset skipped: ${err.message}`);
  } finally {
    await client.end().catch(() => {});
  }
}

try {
  // ------------------------------------------------------------------ health
  section("Health");
  {
    const r = await api("/api/v1/health");
    check("GET /health → 200", r.status === 200, `got ${r.status}`);
  }

  // ------------------------------------------------------------------ module 1
  section("Module 1 — Session & Access");
  const pin = process.env.STAFF_PIN;
  let staffToken = null;

  /* Two-layer table security (sql/005_table_session_security.sql). The whole
     lifecycle runs against TABLE_TOKEN in order: the first scan claims the
     table and mints the credentials, every later scan gets `locked`, three
     wrong PINs flag it, and only the 20-character pass unlocks it again. */
  let sessionPin = null;
  let sessionSecret = null;
  let sessionTableId = null;

  /* Every session entry point now requires a name (the gate collects one
     before it calls anything), so the smoke run identifies itself like a real
     guest instead of relying on a "Guest" fallback. */
  const GUEST = { user_id: "smoke-device", name: "Smoke Tester" };

  {
    const r = await api("/api/v1/sessions/initialize", {
      method: "POST",
      body: { table_token: TABLE_TOKEN, ...GUEST },
    });
    const data = r.body?.data ?? {};
    sessionPin = data.session_pin ?? null;
    sessionSecret = data.session_secret ?? null;
    sessionTableId = data.table_id ?? null;

    check("E1 first scan claims the table → 200", r.status === 200, `got ${r.status}`);
    check("E1 reports the session active", data.status === "active", `got ${data.status}`);
    check("E1 returns the table code", data.code === TABLE_TOKEN);
    check("E1 mints a 2-digit PIN", /^\d{2}$/.test(sessionPin ?? ""), `got ${sessionPin}`);
    check(
      "E1 mints a 20-character pass",
      /^[A-Za-z0-9]{20}$/.test(sessionSecret ?? ""),
      `got length ${sessionSecret?.length}`,
    );
    check("E1 returns a realtime_token field", "realtime_token" in data);

    // The same table QR, scanned by a second phone: no credentials, no data.
    const again = await api("/api/v1/sessions/initialize", {
      method: "POST",
      body: { table_token: TABLE_TOKEN, ...GUEST },
    });
    const locked = again.body?.data ?? {};
    check("E1 second scan of a live table → locked", locked.status === "locked", `got ${locked.status}`);
    check("E1 locked reply reports the PIN unlocked", locked.pin_locked === false);
    check("E1 locked reply releases no pass", !("session_secret" in locked));
    check("E1 locked reply releases no read token", locked.realtime_token === null);
    /* The Chhotu key rides with the credentials and nothing else: a scan of a
       table this device has not joined must not carry it. */
    check("E1 locked reply releases no AI key", !("gemini_api_key" in locked));
    check("E1 locked reply reports 3 attempts", locked.attempts_remaining === 3, `got ${locked.attempts_remaining}`);

    const bad = await api("/api/v1/sessions/initialize", {
      method: "POST",
      body: { table_token: "zzzz", ...GUEST },
    });
    check("E1 unknown token → 404 TABLE_NOT_FOUND", bad.body?.error?.code === "TABLE_NOT_FOUND");

    const malformed = await api("/api/v1/sessions/initialize", {
      method: "POST",
      body: { table_token: "BAD TOKEN!", ...GUEST },
    });
    check("E1 malformed token → 400 VALIDATION_ERROR", malformed.body?.error?.code === "VALIDATION_ERROR");
    check("E1 validation carries error.fields", Boolean(malformed.body?.error?.fields));

    // The name is part of the contract now: an unnamed guest is refused, so a
    // ticket can never be created without someone to attribute it to.
    const unnamed = await api("/api/v1/sessions/initialize", {
      method: "POST",
      body: { table_token: TABLE_TOKEN },
    });
    check("E1 without a name → 400 VALIDATION_ERROR", unnamed.body?.error?.code === "VALIDATION_ERROR", `got ${unnamed.body?.error?.code}`);
    check("E1 name error names the field", Boolean(unnamed.body?.error?.fields?.name), JSON.stringify(unnamed.body?.error?.fields ?? {}));

    const blankName = await api("/api/v1/sessions/initialize", {
      method: "POST",
      body: { table_token: TABLE_TOKEN, user_id: "smoke-device", name: "   " },
    });
    check("E1 whitespace-only name → 400", blankName.body?.error?.code === "VALIDATION_ERROR", `got ${blankName.body?.error?.code}`);
  }

  {
    /* ---- Layer 2 is the UNLOCK, not a shortcut ------------------------
       The table was just claimed and has no failed attempts, so its keypad
       works: a tablemate's pass must be refused outright here. Otherwise a
       photographed QR would replace the 2-digit PIN entirely. */
    const earlyPass = await api("/api/v1/sessions/join-pass", {
      method: "POST",
      body: { table_token: TABLE_TOKEN, secret: sessionSecret, ...GUEST },
    });
    check(
      "E1c pass on an unlocked table → 403 PASS_REQUIRES_PIN",
      earlyPass.body?.error?.code === "PASS_REQUIRES_PIN",
      `got ${earlyPass.body?.error?.code ?? earlyPass.status}`,
    );
    check(
      "E1c refused pass reports all 3 PIN tries left",
      earlyPass.body?.error?.attempts_remaining === 3,
      `got ${earlyPass.body?.error?.attempts_remaining}`,
    );

    // ---- Layer 1: the 2-digit PIN, and the table-wide 3-strike lock ----
    const wrongPin = sessionPin === "00" ? "99" : "00";

    const first = await api("/api/v1/sessions/join-pin", {
      method: "POST",
      body: { table_token: TABLE_TOKEN, pin: wrongPin, ...GUEST },
    });
    check("E1b wrong PIN → 401 INVALID_SESSION_PIN", first.body?.error?.code === "INVALID_SESSION_PIN", `got ${first.body?.error?.code}`);
    check("E1b wrong PIN reports 2 attempts left", first.body?.error?.attempts_remaining === 2, `got ${first.body?.error?.attempts_remaining}`);

    const second = await api("/api/v1/sessions/join-pin", {
      method: "POST",
      body: { table_token: TABLE_TOKEN, pin: wrongPin, ...GUEST },
    });
    check("E1b second wrong PIN → 401", second.body?.error?.code === "INVALID_SESSION_PIN");
    check("E1b second wrong PIN reports 1 attempt left", second.body?.error?.attempts_remaining === 1, `got ${second.body?.error?.attempts_remaining}`);

    // The 3rd wrong PIN IS the lock (confirmed product decision).
    const third = await api("/api/v1/sessions/join-pin", {
      method: "POST",
      body: { table_token: TABLE_TOKEN, pin: wrongPin, ...GUEST },
    });
    check("E1b third wrong PIN → 423 TABLE_PIN_LOCKED", third.body?.error?.code === "TABLE_PIN_LOCKED", `got ${third.body?.error?.code}`);
    check("E1b the lock reports 0 attempts left", third.body?.error?.attempts_remaining === 0, `got ${third.body?.error?.attempts_remaining}`);

    // Even the CORRECT PIN is refused while the table is flagged.
    const correctWhileLocked = await api("/api/v1/sessions/join-pin", {
      method: "POST",
      body: { table_token: TABLE_TOKEN, pin: sessionPin, ...GUEST },
    });
    check("E1b correct PIN while flagged → 423", correctWhileLocked.body?.error?.code === "TABLE_PIN_LOCKED", `got ${correctWhileLocked.body?.error?.code}`);

    const flagged = await api("/api/v1/sessions/initialize", {
      method: "POST",
      body: { table_token: TABLE_TOKEN, ...GUEST },
    });
    check("E1 initialize reports the table flagged", flagged.body?.data?.pin_locked === true);

    const badShape = await api("/api/v1/sessions/join-pin", {
      method: "POST",
      body: { table_token: TABLE_TOKEN, pin: "7", ...GUEST },
    });
    check("E1b one-digit PIN → 400 VALIDATION_ERROR", badShape.body?.error?.code === "VALIDATION_ERROR", `got ${badShape.body?.error?.code}`);

    // ---- Layer 2: the 20-character pass unlocks and unflags ------------
    const wrongPass = sessionSecret === "A".repeat(20) ? "B".repeat(20) : "A".repeat(20);
    const rejected = await api("/api/v1/sessions/join-pass", {
      method: "POST",
      body: { table_token: TABLE_TOKEN, secret: wrongPass, ...GUEST },
    });
    check("E1c wrong pass → 401 INVALID_SESSION_SECRET", rejected.body?.error?.code === "INVALID_SESSION_SECRET", `got ${rejected.body?.error?.code}`);

    const shortPass = await api("/api/v1/sessions/join-pass", {
      method: "POST",
      body: { table_token: TABLE_TOKEN, secret: "too-short", ...GUEST },
    });
    check("E1c 9-character pass → 400 VALIDATION_ERROR", shortPass.body?.error?.code === "VALIDATION_ERROR", `got ${shortPass.body?.error?.code}`);

    const pass = await api("/api/v1/sessions/join-pass", {
      method: "POST",
      body: { table_token: TABLE_TOKEN, secret: sessionSecret, ...GUEST },
    });
    check("E1c correct pass → 200 active", pass.status === 200 && pass.body?.data?.status === "active", `got ${pass.status} / ${pass.body?.data?.status}`);
    check("E1c pass returns the table's PIN", pass.body?.data?.session_pin === sessionPin);
    check(
      "E1c pass releases the AI key field with the credentials",
      "gemini_api_key" in (pass.body?.data ?? {}),
      JSON.stringify(Object.keys(pass.body?.data ?? {})),
    );

    const unflagged = await api("/api/v1/sessions/initialize", {
      method: "POST",
      body: { table_token: TABLE_TOKEN, ...GUEST },
    });
    check("E1c the pass resets the 3-strike flag", unflagged.body?.data?.pin_locked === false);

    const afterUnlock = await api("/api/v1/sessions/join-pin", {
      method: "POST",
      body: { table_token: TABLE_TOKEN, pin: sessionPin, ...GUEST },
    });
    check("E1b correct PIN after an unlock → 200", afterUnlock.body?.data?.status === "active", `got ${afterUnlock.body?.error?.code ?? afterUnlock.body?.data?.status}`);
    /* GEMINI_API_KEY is optional, so the field must ALWAYS be present on a
       granted session but may legitimately be null. When this script can see
       the same key the server was started with, the released value must match
       it exactly — that is the whole contract. */
    const expectedKey = process.env.GEMINI_API_KEY?.trim() || null;
    const grantedKey = afterUnlock.body?.data?.gemini_api_key ?? null;
    check(
      "E1b a joined device receives the AI key",
      "gemini_api_key" in (afterUnlock.body?.data ?? {}) &&
        (grantedKey === null || grantedKey.length > 8) &&
        (expectedKey === null || grantedKey === expectedKey),
      `got ${grantedKey === null ? "null" : `${String(grantedKey).slice(0, 4)}…`}, ` +
        `expected ${expectedKey ? `${expectedKey.slice(0, 4)}…` : "null"}`,
    );

    // ---- Reconnect: a refresh must not re-prompt -----------------------
    const reconnect = await api("/api/v1/sessions/reconnect", {
      method: "POST",
      body: { table_token: TABLE_TOKEN, secret: sessionSecret, ...GUEST },
    });
    check("E1d reconnect with the pass → 200", reconnect.status === 200 && reconnect.body?.data?.status === "active", `got ${reconnect.status}`);
    check(
      "E1d reconnect re-releases the AI key (memory-only on the client)",
      reconnect.body?.data?.gemini_api_key === afterUnlock.body?.data?.gemini_api_key,
    );

    const stale = await api("/api/v1/sessions/reconnect", {
      method: "POST",
      body: { table_token: TABLE_TOKEN, secret: wrongPass, ...GUEST },
    });
    check("E1d reconnect with a stale pass → 403 SESSION_ENDED", stale.body?.error?.code === "SESSION_ENDED", `got ${stale.body?.error?.code}`);
  }

  {
    // A test must never encode the real PIN — CI runs with a dummy value.
    // Derive a candidate that is guaranteed wrong for whatever STAFF_PIN is set.
    const wrongPin = pin === "000000" ? "999999" : "000000";
    const wrong = await api("/api/v1/auth/kds-login", { method: "POST", body: { pin: wrongPin } });
    check("E2 wrong PIN → 401 INVALID_PIN", wrong.body?.error?.code === "INVALID_PIN", `got ${wrong.body?.error?.code}`);

    if (!pin) {
      check("STAFF_PIN available in backend/.env", false, "var missing");
    } else {
      const ok = await api("/api/v1/auth/kds-login", { method: "POST", body: { pin } });
      check("E2 correct PIN → 200", ok.status === 200, `got ${ok.status}`);
      check("E2 role claim is kitchen", ok.body?.data?.role === "kitchen");
      staffToken = ok.body?.data?.token ?? null;
      check("E2 issues a bearer token", typeof staffToken === "string" && staffToken.split(".").length === 3);

      const me = await api("/api/v1/auth/me", { token: staffToken });
      check("E2b /auth/me → 200 authenticated", me.body?.data?.authenticated === true);
      check("E2b never echoes a secret", !JSON.stringify(me.body).toLowerCase().includes("pin"));
    }
  }

  // ------------------------------------------------------------------ module 2
  section("Module 2 — Menu & Shared Cart");
  let menu = [];

  {
    const r = await api(`/api/v1/menu?table_token=${TABLE_TOKEN}&limit=100`);
    menu = r.body?.data ?? [];
    check("E3 menu → 200", r.status === 200, `got ${r.status}`);
    /* The seed's dish count moves with the menu, so the assertion is that
       the walk reached everything meta.total promised — not a frozen number. */
    check("E3 menu walk returns dishes", menu.length > 0, `got ${menu.length}`);
    check(
      "E3 menu walk reaches meta.total",
      menu.length === r.body?.meta?.total,
      `got ${menu.length} row(s), meta.total ${r.body?.meta?.total}`,
    );
    check("E3 rows use menu_item_id naming", menu[0] && "menu_item_id" in menu[0]);
  }

  const target = menu.find((m) => m.name === "Masala Dosa") ?? menu[0];
  let cartLineId = null;

  {
    const r = await api(`/api/v1/cart/items?table_token=${TABLE_TOKEN}&limit=100`);
    check("E4 cart read → 200", r.status === 200, `got ${r.status}`);
    check("E4 meta is present", Boolean(r.body?.meta));
  }

  {
    // 86 the target first so the availability guard is provable.
    const off = await api(`/api/v1/menu/items/${target.menu_item_id}/availability`, {
      method: "PATCH",
      token: staffToken,
      body: { is_available: false },
    });
    check("E14 86 an item → 200", off.body?.data?.is_available === false);

    const blocked = await api("/api/v1/cart/items", {
      method: "POST",
      body: {
        table_token: TABLE_TOKEN,
        menu_item_id: target.menu_item_id,
        quantity: 1,
        added_by: GUEST.name,
      },
    });
    check("E5 86'd item → 409 ITEM_UNAVAILABLE", blocked.body?.error?.code === "ITEM_UNAVAILABLE", `got ${blocked.body?.error?.code}`);

    const on = await api(`/api/v1/menu/items/${target.menu_item_id}/availability`, {
      method: "PATCH",
      token: staffToken,
      body: { is_available: true },
    });
    check("E14 un-86 → 200", on.body?.data?.is_available === true);
  }

  {
    const add = await api("/api/v1/cart/items", {
      method: "POST",
      body: {
        table_token: TABLE_TOKEN,
        menu_item_id: target.menu_item_id,
        quantity: 2,
        added_by: "smoke",
        allergy_note: "NO PEANUTS - SMOKE TEST",
      },
    });
    cartLineId = add.body?.data?.id ?? null;
    check("E5 add to cart → 200", add.status === 200, `got ${add.status}`);
    check("E5 quantity is 2", add.body?.data?.quantity === 2, `got ${add.body?.data?.quantity}`);
    check("E5 returns total_table_quantity", typeof add.body?.data?.total_table_quantity === "number");

    // Same columns → the UNIQUE index + ON CONFLICT must MERGE, not fork.
    const merge = await api("/api/v1/cart/items", {
      method: "POST",
      body: {
        table_token: TABLE_TOKEN,
        menu_item_id: target.menu_item_id,
        quantity: 1,
        added_by: GUEST.name,
        allergy_note: "NO PEANUTS - SMOKE TEST",
      },
    });
    check("E5 duplicate tap merges (2+1=3)", merge.body?.data?.quantity === 3, `got ${merge.body?.data?.quantity}`);
    check("E5 merge reuses the same row id", merge.body?.data?.id === cartLineId);
  }

  {
    const delta = await api(`/api/v1/cart/items/${cartLineId}`, {
      method: "PATCH",
      body: { table_token: TABLE_TOKEN, quantity_delta: 2 },
    });
    check("E6 quantity_delta applied atomically", delta.body?.data?.quantity === 5, `got ${delta.body?.data?.quantity}`);

    const over = await api(`/api/v1/cart/items/${cartLineId}`, {
      method: "PATCH",
      body: { table_token: TABLE_TOKEN, quantity_delta: 200 },
    });
    check("E6 out-of-range delta → 400", over.status === 400, `got ${over.status}`);
  }

  // Foreign-table isolation: a different token must not see or touch this line.
  {
    const foreign = await api(`/api/v1/cart/items/${cartLineId}`, {
      method: "PATCH",
      body: { table_token: FOREIGN_TABLE_TOKEN, quantity: 1 },
    });
    check("E6 foreign table → 404 CART_ITEM_NOT_FOUND", foreign.body?.error?.code === "CART_ITEM_NOT_FOUND", `got ${foreign.body?.error?.code}`);
  }

  // ------------------------------------------------------------------ module 3 + fire
  section("Module 3 — Fire & Kitchen Display");
  let orderId = null;

  {
    const fire = await api("/api/v1/orders/fire", { method: "POST", body: { table_token: TABLE_TOKEN } });
    orderId = fire.body?.data?.order_id ?? null;
    check("E8 fire → 201", fire.status === 201, `got ${fire.status}`);
    check("E8 status is pending", fire.body?.data?.status === "pending");
    check("E8 cart drained after fire", (await api(`/api/v1/cart/items?table_token=${TABLE_TOKEN}`)).body?.data?.length === 0);

    const dupe = await api("/api/v1/orders/fire", { method: "POST", body: { table_token: TABLE_TOKEN } });
    check("E8 duplicate fire → 409 DUPLICATE_ORDER", dupe.body?.error?.code === "DUPLICATE_ORDER", `got ${dupe.body?.error?.code}`);

    /* E16 is scoped to the CURRENT seating, and the frozen bill must be on it
       while the party is still sitting there (docs/14 #21). */
    const seating = await api(`/api/v1/orders?table_token=${TABLE_TOKEN}&limit=100`);
    const seatingRow = (seating.body?.data ?? []).find((o) => o.order_id === orderId);
    const seatingLine = seatingRow?.items?.[0];
    check("E16 history has this seating's order", Boolean(seatingRow));
    check(
      "E16 history carries the fire-time unit price",
      seatingLine?.unit_price === target.price,
      `got ${seatingLine?.unit_price} expected ${target.price}`,
    );
    check(
      "E16 frozen total equals qty x unit price",
      seatingRow?.total === (seatingLine?.quantity ?? 0) * target.price,
      `got total ${seatingRow?.total} for qty ${seatingLine?.quantity} @ ${target.price}`,
    );
    check("E8 duplicate carries error.order_id", dupe.body?.error?.order_id === orderId);

    const active = await api(`/api/v1/sessions/${TABLE_TOKEN}/active-check`);
    check("E9 active-check reports the block", active.body?.data?.has_active_order === true);

    // E17 while the ticket is LIVE — the floor card depends on these items to
    // show allergy alerts, so assert the shape here (after pruning the order
    // is served and active_order becomes null).
    const floorLive = await api("/api/v1/floor/tables?limit=100", { token: staffToken });
    const liveRow = (floorLive.body?.data ?? []).find((t) => t.code === TABLE_TOKEN);

    /* ZERO-KNOWLEDGE: the floor board and the kitchen board must never carry
       the table's credentials — not the column names, and not the values. */
    const floorJson = JSON.stringify(floorLive.body ?? {});
    check("E17 never exposes session_pin", !floorJson.includes("session_pin"));
    check("E17 never exposes session_secret", !floorJson.includes("session_secret"));
    check(
      "E17 never leaks the pass value",
      !sessionSecret || !floorJson.includes(sessionSecret),
    );
    check("E17 active_order carries the ticket items", Array.isArray(liveRow?.active_order?.items));
    check(
      "E17 items carry the allergy note",
      liveRow?.active_order?.items?.[0]?.allergy_note === "NO PEANUTS - SMOKE TEST",
      `got ${JSON.stringify(liveRow?.active_order?.items?.[0]?.allergy_note)}`,
    );
    check(
      "E17 items carry the dish name (live join)",
      typeof liveRow?.active_order?.items?.[0]?.name === "string" &&
        liveRow.active_order.items[0].name.length > 0,
    );

    const status = await api(`/api/v1/orders/${orderId}/status?table_token=${TABLE_TOKEN}`);
    check("E15 status → 200 pending", status.body?.data?.status === "pending");

    const unscoped = await api(`/api/v1/orders/${orderId}/status?table_token=${FOREIGN_TABLE_TOKEN}`);
    check("E15 foreign table → 404 ORDER_NOT_FOUND", unscoped.body?.error?.code === "ORDER_NOT_FOUND");
  }

  {
    const noAuth = await api("/api/v1/kds/tickets");
    check("E10 without token → 401 UNAUTHORIZED", noAuth.body?.error?.code === "UNAUTHORIZED", `got ${noAuth.body?.error?.code}`);

    const garbage = await api("/api/v1/kds/tickets", { token: "not.a.jwt" });
    check("E10 garbage token → 401 UNAUTHORIZED", garbage.body?.error?.code === "UNAUTHORIZED");

    const board = await api("/api/v1/kds/tickets?limit=100", { token: staffToken });
    check("E10 with staff token → 200", board.status === 200, `got ${board.status}`);
    const ticket = (board.body?.data ?? []).find((t) => t.order_id === orderId);
    check("E10 board contains the fired ticket", Boolean(ticket));
    check("E10 ticket joins the table code", ticket?.table?.code === TABLE_TOKEN);
    check("E10 ticket carries the allergy note", ticket?.items?.[0]?.allergy_note === "NO PEANUTS - SMOKE TEST");

    // PRICE SNAPSHOT (sql/004_hardening.sql): the ticket must carry the price
    // charged at fire time, not a hardcoded 0 and not a later menu edit.
    check(
      "E10 ticket carries the fire-time unit price",
      ticket?.items?.[0]?.unit_price === target.price,
      `got ${ticket?.items?.[0]?.unit_price} expected ${target.price}`,
    );

    const boardJson = JSON.stringify(board.body ?? {});
    check("E10 never exposes session_pin", !boardJson.includes("session_pin"));
    check("E10 never exposes session_secret", !boardJson.includes("session_secret"));
    check(
      "E10 never leaks the pass value",
      !sessionSecret || !boardJson.includes(sessionSecret),
    );
  }

  {
    const early = await api(`/api/v1/kds/tickets/${orderId}/prune`, { method: "PATCH", token: staffToken });
    check("E12 prune before ready → 409 INVALID_STATUS_TRANSITION", early.body?.error?.code === "INVALID_STATUS_TRANSITION", `got ${early.body?.error?.code}`);
    check("E12 carries current_status", early.body?.error?.current_status === "pending");

    const skip = await api(`/api/v1/kds/tickets/${orderId}/status`, {
      method: "PATCH",
      token: staffToken,
      body: { status: "ready" },
    });
    check("E11 skipping a step → 409", skip.body?.error?.code === "INVALID_STATUS_TRANSITION");

    const prep = await api(`/api/v1/kds/tickets/${orderId}/status`, {
      method: "PATCH",
      token: staffToken,
      body: { status: "preparing" },
    });
    check("E11 pending→preparing → 200", prep.body?.data?.status === "preparing");

    const repeat = await api(`/api/v1/kds/tickets/${orderId}/status`, {
      method: "PATCH",
      token: staffToken,
      body: { status: "preparing" },
    });
    check("E11 repeating a step → 409", repeat.body?.error?.code === "INVALID_STATUS_TRANSITION");

    const ready = await api(`/api/v1/kds/tickets/${orderId}/status`, {
      method: "PATCH",
      token: staffToken,
      body: { status: "ready" },
    });
    check("E11 preparing→ready → 200", ready.body?.data?.status === "ready");

    const prune = await api(`/api/v1/kds/tickets/${orderId}/prune`, { method: "PATCH", token: staffToken });
    check("E12 prune → served", prune.body?.data?.status === "served");
    check(
      "E12 serving the last ticket keeps the table (bill unpaid)",
      prune.body?.data?.table_cleared === false,
      `got ${prune.body?.data?.table_cleared}`,
    );
  }

  /* ---- Bill settlement → device disconnect → auto-release -------------
     The table is paid and empty, but a device is still connected, so the
     first settle must NOT release it. Removing the heartbeat is the final
     condition; only then are the credentials and the cart cleared. */
  {
    const heartbeat = await api(`/api/v1/sessions/${TABLE_TOKEN}/heartbeat`, {
      method: "POST",
      body: { device_id: "smoke-device" },
    });
    check("heartbeat registers a device → 200", heartbeat.status === 200, `got ${heartbeat.status}`);
    check("heartbeat echoes the device", heartbeat.body?.data?.device_id === "smoke-device");

    const bill = await api(`/api/v1/sessions/${TABLE_TOKEN}/bill-request`, { method: "POST" });
    check("bill request → 200", bill.status === 200, `got ${bill.status}`);
    check("bill request sets 'requested'", bill.body?.data?.bill_status === "requested", `got ${bill.body?.data?.bill_status}`);
    check(
      "bill request stamps bill_requested_at",
      Boolean(bill.body?.data?.bill_requested_at),
    );

    const settle = await api(`/api/v1/floor/tables/${sessionTableId}/settle`, {
      method: "PATCH",
      token: staffToken,
    });
    check("settle → 200 paid", settle.status === 200 && settle.body?.data?.bill_status === "paid", `got ${settle.status} / ${settle.body?.data?.bill_status}`);
    check(
      "settle with a connected device does NOT release",
      settle.body?.data?.released === false,
      `got ${settle.body?.data?.released}`,
    );

    const disconnect = await api(`/api/v1/sessions/${TABLE_TOKEN}/heartbeat`, {
      method: "DELETE",
      body: { device_id: "smoke-device" },
    });
    check("device disconnect → 200", disconnect.status === 200, `got ${disconnect.status}`);
    check(
      "last device disconnect auto-releases the paid table",
      disconnect.body?.data?.released === true,
      `got ${disconnect.body?.data?.released}`,
    );

    /* The release ENDS the session: the credentials must be gone from the
       row, so the next party's first scan mints a fresh pair instead of
       inheriting one that an old device could still reconnect with. Read
       straight from the DB because the API never exposes these columns. */
    if (process.env.DATABASE_URL) {
      const db = new pg.Client({ connectionString: process.env.DATABASE_URL.trim() });
      try {
        await db.connect();
        const { rows } = await db.query(
          `SELECT status, session_pin, session_secret, failed_pin_attempts,
                  bill_status, bill_paid_at
             FROM restaurant_tables WHERE code = $1`,
          [TABLE_TOKEN],
        );
        const row = rows[0] ?? {};
        check("auto-release clears session_pin", row.session_pin === null, `got ${row.session_pin}`);
        check("auto-release clears session_secret", row.session_secret === null, `got ${row.session_secret}`);
        check("auto-release resets failed_pin_attempts", row.failed_pin_attempts === 0, `got ${row.failed_pin_attempts}`);
        check("auto-release leaves the table empty", row.status === "empty", `got ${row.status}`);
        check("auto-release resets bill_status", row.bill_status === "unrequested", `got ${row.bill_status}`);
        check("auto-release clears bill_paid_at", row.bill_paid_at === null, `got ${row.bill_paid_at}`);
      } catch (err) {
        check("auto-release verified against the database", false, err.message);
      } finally {
        await db.end().catch(() => {});
      }
    }
  }

  {
    // The next party's scan starts from a genuinely fresh credential pair.
    const fresh = await api("/api/v1/sessions/initialize", {
      method: "POST",
      body: { table_token: TABLE_TOKEN, ...GUEST },
    });
    check("E1 next scan claims the released table", fresh.body?.data?.status === "active", `got ${fresh.body?.data?.status}`);
    check(
      "E1 released table mints a new pass",
      fresh.body?.data?.session_secret && fresh.body.data.session_secret !== sessionSecret,
    );
  }

  {
    const after = await api(`/api/v1/sessions/${TABLE_TOKEN}/active-check`);
    check("E9 table is free again after serving", after.body?.data?.has_active_order === false);
  }

  // ------------------------------------------------------------------ module 4
  section("Module 4 — Floor, history, shift");

  {
    const noAuth = await api("/api/v1/floor/tables");
    check("E17 without token → 401 UNAUTHORIZED", noAuth.body?.error?.code === "UNAUTHORIZED");

    const floor = await api("/api/v1/floor/tables?limit=100", { token: staffToken });
    check("E17 with staff token → 200", floor.status === 200, `got ${floor.status}`);
    check("E17 returns all 5 tables", (floor.body?.data ?? []).length === 5, `got ${(floor.body?.data ?? []).length}`);
    check("E17 table exposes cart_line_count", "cart_line_count" in (floor.body?.data?.[0] ?? {}));

    /* The auto-release above handed this table to its next party. Orders die
       with the seating (docs/14 #21), so a freshly-scanned table must show an
       EMPTY history — never the previous party's food. Revenue survives in
       the sales rollup that admin analytics reads (sql/012). */
    const history = await api(`/api/v1/orders?table_token=${TABLE_TOKEN}&limit=100`);
    check(
      "E16 after a clear returns no previous-party orders",
      (history.body?.data ?? []).length === 0,
      `got ${(history.body?.data ?? []).length} row(s)`,
    );

    const shift = await api("/api/v1/kds/shift/activate", {
      method: "POST",
      token: staffToken,
      body: { device_id: "smoke-runner" },
    });
    check("E13 activate shift → audio_armed", shift.body?.data?.audio_armed === true);

    const badStatus = await api(`/api/v1/kds/tickets/${orderId}/status`, {
      method: "PATCH",
      token: staffToken,
      body: { status: "served" },
    });
    check("E11 rejects `served` (prune-only)", badStatus.status === 400, `got ${badStatus.status}`);
  }

  {
    const unknown = await api("/api/v1/nope");
    check("unknown route → 404 NOT_FOUND", unknown.body?.error?.code === "NOT_FOUND");
    check("error envelope carries success:false", unknown.body?.success === false);
  }
} catch (err) {
  console.error(`\n[smoke] aborted: ${err.message}`);
  failures.push(`runner crashed: ${err.message}`);
}

